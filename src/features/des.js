/** permute: out[i] = bits[table[i] - 1] */
const permute = (bits, table) => table.map(i => bits[i - 1])

/** বাইট → বিটের Array (MSB আগে) */
function bytesToBits(bytes) {
  const out = []
  for (const b of bytes) for (let i = 7; i >= 0; i--) out.push((b >> i) & 1)
  return out
}

/** বিটের Array → বাইট */
function bitsToBytes(bits) {
  const out = []
  for (let i = 0; i < bits.length; i += 8) {
    let v = 0
    for (let j = 0; j < 8; j++) v = (v << 1) | (bits[i + j] || 0)
    out.push(v & 0xff)
  }
  return out
}

const xor = (a, b) => a.map((v, i) => v ^ b[i])
const rotl = (arr, n) => arr.slice(n).concat(arr.slice(0, n))

/** ১৬টা সাব-কি বানানো */
function keySchedule(keyBytes) {
  const k = permute(bytesToBits(keyBytes), PC1)
  let c = k.slice(0, 28)
  let d = k.slice(28)
  const subs = []
  for (let i = 0; i < 16; i++) {
    c = rotl(c, SHIFTS[i])
    d = rotl(d, SHIFTS[i])
    subs.push(permute(c.concat(d), PC2))
  }
  return subs
}

/** Feistel ফাংশন */
function f(r, k) {
  const e = permute(r, E)
  const x = xor(e, k)
  let out = []
  for (let i = 0; i < 8; i++) {
    const chunk = x.slice(i * 6, i * 6 + 6)
    const row = (chunk[0] << 1) | chunk[5]
    const col = (chunk[1] << 3) | (chunk[2] << 2) | (chunk[3] << 1) | chunk[4]
    const v = SBOX[i][row * 16 + col]
    for (let j = 3; j >= 0; j--) out.push((v >> j) & 1)
  }
  return permute(out, P)
}

/** একটা ৮-বাইট ব্লক ডিক্রিপ্ট */
function decryptBlock(block, subs) {
  const ip = permute(bytesToBits(block), IP)
  let l = ip.slice(0, 32)
  let r = ip.slice(32)
  for (let i = 0; i < 16; i++) {
    const prev = r
    r = xor(l, f(r, subs[15 - i]))
    l = prev
  }
  return bitsToBytes(permute(r.concat(l), FP))
}

/**
 * DES-ECB ডিক্রিপ্ট (PKCS7 প্যাডিং সরিয়ে) — স্ট্রিং ফেরত দেয়
 * @param {string|Buffer} b64 base64 এনকোডেড ডেটা
 * @param {string} keyStr ৮ অক্ষরের কি
 */
export function desEcbDecrypt(b64, keyStr) {
  const data = Buffer.from(String(b64), 'base64')
  if (data.length === 0 || data.length % 8 !== 0) return null
  const key = Buffer.from(String(keyStr), 'utf8')
  if (key.length < 8) return null

  const subs = keySchedule(key.subarray(0, 8))
  const out = []
  for (let i = 0; i < data.length; i += 8) {
    out.push(...decryptBlock(data.subarray(i, i + 8), subs))
  }

  // PKCS7 প্যাডিং সরাও।
  // ⚠️ শুধু শেষ বাইট দেখে কেটে দিলে ভুল হতে পারে — আসল URL-এর শেষ
  //    অক্ষরটা ১-৮ হলে সেটাও প্যাডিং ভেবে কেটে ফেলা হতো।
  //    তাই চেক করি: সব প্যাডিং বাইট কি সত্যিই `pad`-এর সমান।
  const pad = out[out.length - 1]
  if (pad > 0 && pad <= 8) {
    const tail = out.slice(out.length - pad)
    if (tail.every(b => b === pad)) {
      return Buffer.from(out.slice(0, out.length - pad)).toString('utf8')
    }
  }
  return Buffer.from(out).toString('utf8')
}
